const CACHE_PREFIX = 'naqra-sawa-';
const CACHE = CACHE_PREFIX + VERSION;
const SHELL = 'index.html';
const NAV_TIMEOUT_MS = 4000;

const SCOPE = self.registration.scope; // e.g. https://user.github.io/repo/
const abs = (p) => new URL(p, SCOPE).href;
const PRECACHED = new Set(PRECACHE.map(([p]) => abs(p)));
const SHELL_URL = abs(SHELL);

const cacheable = (res) => res && res.ok && res.type === 'basic' && !res.redirected;

/* ---------- lifecycle ---------- */

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      await Promise.all(
        PRECACHE.map(async ([path, rev]) => {
          // The revision query defeats the HTTP cache and the CDN, so a fresh worker never stores a stale file.
          const res = await fetch(abs(path) + (rev ? '?__v=' + rev : ''), { cache: 'no-store', credentials: 'same-origin' });
          if (!res.ok) throw new Error('precache failed: ' + path + ' (' + res.status + ')');
          await cache.put(abs(path), res);
        })
      );
    })()
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((k) => k.startsWith(CACHE_PREFIX) && k !== CACHE).map((k) => caches.delete(k)));
      if (self.registration.navigationPreload) {
        try {
          await self.registration.navigationPreload.enable();
        } catch (e) {}
      }
      await self.clients.claim();
    })()
  );
});

self.addEventListener('message', (event) => {
  const msg = event.data || {};
  if (msg.type === 'SKIP_WAITING') self.skipWaiting();
  else if (msg.type === 'GET_VERSION' && event.ports && event.ports[0]) event.ports[0].postMessage({ version: VERSION });
});

/* ---------- fetch ---------- */

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // Supabase & co: straight to the network, never cached
  if (!url.href.startsWith(SCOPE)) return; // other projects on the same github.io origin
  if (req.headers.has('range')) return;
  if (req.cache === 'only-if-cached' && req.mode !== 'same-origin') return;

  if (req.mode === 'navigate') event.respondWith(navigation(event, url));
  else if (PRECACHED.has(url.href)) event.respondWith(precached(event));
  else event.respondWith(staleWhileRevalidate(event));
});

function isShell(url) {
  const path = url.origin + url.pathname;
  return path === SCOPE || path === SHELL_URL;
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const noop = () => {};

async function navigation(event, url) {
  const cache = await caches.open(CACHE);
  const shell = isShell(url);
  const network = (async () => {
    const res = (await event.preloadResponse) || (await fetch(event.request));
    if (res.status >= 500) throw new Error('server error ' + res.status);
    if (cacheable(res)) await cache.put(shell ? SHELL_URL : event.request, res.clone());
    return res;
  })();
  event.waitUntil(network.then(noop, noop)); // a slow response still refreshes the cache after we fell back
  const first = await Promise.race([network.catch(() => null), sleep(NAV_TIMEOUT_MS)]);
  if (first) return first;
  // Offline, server error or too slow: serve the cached shell.
  const cached = (shell ? null : await cache.match(event.request, { ignoreSearch: true })) || (await cache.match(SHELL_URL));
  return cached || network; // nothing cached: keep waiting for the network (or surface its error)
}

async function precached(event) {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(event.request, { ignoreVary: true });
  return hit || staleWhileRevalidate(event);
}

async function staleWhileRevalidate(event) {
  const req = event.request;
  const cache = await caches.open(CACHE);
  const hit = await cache.match(req);
  // Revalidate past the HTTP cache so a stale browser copy never overwrites a fresher cached one.
  const network = fetch(new Request(req, { cache: 'no-cache' })).then(async (res) => {
    if (cacheable(res)) await cache.put(req, res.clone());
    return res;
  });
  if (hit) {
    event.waitUntil(network.then(noop, noop));
    return hit;
  }
  return network;
}

/* ---------- Web Push ---------- */

self.addEventListener('push', (event) => {
  let data = {};
  if (event.data) {
    try {
      data = event.data.json() || {};
    } catch (e) {
      data = { body: event.data.text() };
    }
  }
  const options = {
    body: data.body || '',
    icon: abs('icons/icon-192.png'),
    badge: abs('icons/badge-96.png'),
    lang: 'ar',
    dir: 'rtl',
    data: { url: data.url || '' },
  };
  if (data.tag) {
    options.tag = String(data.tag);
    options.renotify = true;
  }
  event.waitUntil(self.registration.showNotification(data.title || 'نقرأ سوا', options));
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const wanted = (event.notification.data && event.notification.data.url) || '';
  const target = abs(wanted || './');
  event.waitUntil(
    (async () => {
      const wins = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
      const mine = wins.filter((c) => c.url.startsWith(SCOPE));
      const client = mine.find((c) => c.focused) || mine.find((c) => c.visibilityState === 'visible') || mine[0];
      if (!client) {
        if (self.clients.openWindow) await self.clients.openWindow(target);
        return;
      }
      try {
        await client.focus();
      } catch (e) {}
      if (wanted && client.url !== target) {
        try {
          await client.navigate(target); // only works for windows this worker controls
        } catch (e) {
          client.postMessage({ type: 'NAVIGATE', url: target });
        }
      }
    })()
  );
});
