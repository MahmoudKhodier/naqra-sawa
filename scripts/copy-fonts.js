#!/usr/bin/env node
/* Copies the self-hosted web fonts from the @fontsource packages into site/fonts/
   and writes site/fonts/fonts.css. Only the "arabic" and "latin" subsets (woff2) are kept,
   so the APK and the offline PWA never need Google Fonts.

   Usage: npm run build:fonts   (after npm install; the output is committed) */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'site', 'fonts');
const SUBSETS = ['arabic', 'latin']; // declaration order matters: same as Google Fonts / fontsource

const FAMILIES = [
  { pkg: 'ibm-plex-sans-arabic', family: 'IBM Plex Sans Arabic', weights: [400, 500, 600, 700] },
  { pkg: 'el-messiri', family: 'El Messiri', weights: [500, 600, 700] },
  { pkg: 'amiri', family: 'Amiri', weights: [400, 700] },
];

fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(OUT)) {
  if (/\.(woff2|css)$/.test(f) || /^OFL-.*\.txt$/.test(f)) fs.unlinkSync(path.join(OUT, f));
}

const css = [
  '/* Self-hosted fonts for نقرأ سوا, generated by scripts/copy-fonts.js from @fontsource packages. Do not edit by hand.',
  '   Licence: SIL Open Font License 1.1 (see the OFL-*.txt files next to this one). */',
  '',
];
let total = 0;

for (const { pkg, family, weights } of FAMILIES) {
  const dir = path.join(ROOT, 'node_modules', '@fontsource', pkg);
  if (!fs.existsSync(dir)) throw new Error(`Missing node_modules/@fontsource/${pkg}; run npm install first.`);
  const ranges = JSON.parse(fs.readFileSync(path.join(dir, 'unicode.json'), 'utf8'));
  const version = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')).version;
  css.push(`/* ${family} (@fontsource/${pkg}@${version}) */`);
  for (const weight of weights) {
    for (const subset of SUBSETS) {
      if (!ranges[subset]) throw new Error(`${pkg} has no "${subset}" subset`);
      const file = `${pkg}-${subset}-${weight}-normal.woff2`;
      const src = path.join(dir, 'files', file);
      if (!fs.existsSync(src)) throw new Error(`Missing ${src}`);
      fs.copyFileSync(src, path.join(OUT, file));
      total += fs.statSync(src).size;
      css.push(
        '@font-face {',
        `  font-family: '${family}';`,
        '  font-style: normal;',
        `  font-weight: ${weight};`,
        '  font-display: swap;',
        `  src: url(./${file}) format('woff2');`,
        `  unicode-range: ${ranges[subset]};`,
        '}',
      );
    }
  }
  css.push('');
  for (const lic of ['LICENSE', 'LICENSE.md', 'OFL.txt']) {
    const p = path.join(dir, lic);
    if (fs.existsSync(p)) {
      fs.copyFileSync(p, path.join(OUT, `OFL-${pkg}.txt`));
      break;
    }
  }
}

fs.writeFileSync(path.join(OUT, 'fonts.css'), css.join('\n'));
console.log(`fonts: wrote site/fonts/fonts.css and ${FAMILIES.reduce((n, f) => n + f.weights.length * SUBSETS.length, 0)} woff2 files (${(total / 1024).toFixed(0)} KiB)`);
